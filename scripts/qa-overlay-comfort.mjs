// Kiểm tra các tình huống gây khó chịu: âm báo lặp và zoom bị ghi đè.
import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';
import {minimapZoom} from '../src/lib/minimap-zoom.ts';
const result=await build({entryPoints:['src/lib/companion.ts'],bundle:true,write:false,format:'esm',platform:'node'});
const {AlertEpisodes}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
const capability=JSON.parse(await readFile('src-tauri/capabilities/dino-hud.json','utf8'));
assert.deepEqual(capability.windows,['dino-hud']);
assert.ok(capability.permissions.includes('core:event:default'));
assert.ok(capability.permissions.includes('core:window:allow-is-visible'));
const gate=new AlertEpisodes();
assert.equal(gate.take(['hp'],0,60,true),true);
assert.equal(gate.take(['hp'],61000,60,true),false,'Không kêu lại khi máu vẫn thấp');
assert.equal(gate.take(['hp','water'],62000,60,true),true,'Cảnh báo mới vẫn được báo');
assert.equal(gate.take(['hp','water'],120000,60,false),false,'HUD ẩn không phát âm');
assert.equal(gate.take(['hp','water'],121000,60,true),false,'Không phát bù khi hiện lại');
gate.take([],127000,60,true);
assert.equal(gate.take(['hp'],128000,60,true),true,'Hồi phục đủ lâu rồi thấp lại là đợt mới');
gate.take([],129000,60,true);
assert.equal(gate.take(['hp'],130000,60,true),false,'Không lặp vì một nhịp dữ liệu thiếu');
let frames=new Map(),id=0,radius=600,saves=[];
globalThis.requestAnimationFrame=fn=>{frames.set(++id,fn);return id;};
globalThis.cancelAnimationFrame=id=>frames.delete(id);
const zoom=minimapZoom(()=>radius,v=>radius=v,v=>saves.push(v));
zoom.change(-.5);zoom.sync(1200);
for(const fn of frames.values())fn(16);
await new Promise(r=>setTimeout(r,380));
assert.equal(radius,1200);assert.equal(saves.length,0,'Đổi bố cục hủy lần lưu zoom cũ');
zoom.change(-.5);zoom.dispose();zoom.change(.5);
assert.equal(frames.size,1,'Zoom hoạt động lại sau khi cửa sổ phục hồi');
zoom.dispose();
console.log('PASS: one sound per episode, hidden HUD silence, no replay on show, recovery hysteresis, zoom external override and lifecycle.');
